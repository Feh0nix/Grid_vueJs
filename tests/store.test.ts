import { strict as assert } from 'node:assert'
import { createPinia, setActivePinia } from 'pinia'
import { useSpreadsheetStore } from '../src/stores/useSpreadsheetStore'
import { cellKey } from '../src/utils/helpers'

const storage = new Map<string, string>()
Object.assign(globalThis, { localStorage: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value) } })
setActivePinia(createPinia())
const store = useSpreadsheetStore()
assert.equal(store.renameSheet(store.spreadsheet.activeSheetId, 'Budget'), true)
assert.equal(store.renameSheet(store.spreadsheet.activeSheetId, 'bad/name'), false)
const budgetId = store.spreadsheet.activeSheetId
store.addSheet()
assert.equal(store.renameSheet(store.spreadsheet.activeSheetId, 'budget'), false)
const secondId = store.spreadsheet.activeSheetId
store.updateCellValue({ row: 1, col: 1 }, "=Budget!A3+'Budget'!$B$3+A3")
store.setActiveSheet(budgetId)
store.selectCell({ row: 2, col: 1 })
store.insertRow()
assert.equal(store.sheetsData[secondId][cellKey(1, 1)].formula, "=Budget!A4+'Budget'!$B$4+A3")
store.undo()
assert.equal(store.sheetsData[secondId][cellKey(1, 1)].formula, "=Budget!A3+'Budget'!$B$3+A3")
assert.equal(store.renameSheet(budgetId, 'Budget 2026'), true)
assert.equal(store.sheetsData[secondId][cellKey(1, 1)].formula, "='Budget 2026'!A3+'Budget 2026'!$B$3+A3")
store.undo()
assert.equal(store.sheetsData[secondId][cellKey(1, 1)].formula, "=Budget!A3+'Budget'!$B$3+A3")
store.setActiveSheet(store.spreadsheet.sheets[0].id)
store.selectRange({ sri: 2, sci: 1, eri: 2, eci: 2 })
store.mergeCells()
store.selectCell({ row: 1, col: 1 })
store.insertRow()
assert.equal(store.activeSheet.merges.get(cellKey(3, 1))?.row, 3)
assert.equal(store.activeSheet.merges.has(cellKey(2, 1)), false)
store.deleteRow()
assert.equal(store.activeSheet.merges.get(cellKey(2, 1))?.row, 2)
store.selectCell({ row: 2, col: 2 })
store.freezePanes()
assert.deepEqual(store.spreadsheet.sheets[0].freeze, { row: 1, col: 1 })
store.freezePanes()
assert.equal(store.spreadsheet.sheets[0].freeze, undefined)
assert.equal(store.saveWorkbook(), true)
assert.ok(storage.size)
store.updateCellValue({ row: 1, col: 1 }, 'first')
store.updateCellValue({ row: 1, col: 2 }, 'second')
store.selectCell({ row: 1, col: 1 })
store.copy()
store.selectCell({ row: 2, col: 1 })
store.paste()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(2, 1)].value, 'first')
store.selectRange({ sri: 1, sci: 1, eri: 1, eci: 2 })
store.cut()
store.selectCell({ row: 1, col: 2 })
store.paste()
const cells = store.sheetsData[store.spreadsheet.activeSheetId]
assert.equal(cells[cellKey(1, 1)], undefined)
assert.equal(cells[cellKey(1, 2)].value, 'first')
assert.equal(cells[cellKey(1, 3)].value, 'second')
store.selectCell({ row: 5, col: 1 })
store.pasteText('alpha\tbeta\r\ngamma\tdelta')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(6, 2)].value, 'delta')
store.selectRange({ sri: 5, sci: 1, eri: 6, eci: 2 })
assert.equal(store.selectionAsText(), 'alpha\tbeta\r\ngamma\tdelta')
store.updateCellValue({ row: 10, col: 1 }, '3')
store.updateCellValue({ row: 10, col: 2 }, 'three')
store.updateCellValue({ row: 11, col: 1 }, '1')
store.updateCellValue({ row: 12, col: 1 }, '2')
store.updateCellValue({ row: 12, col: 2 }, 'two')
store.selectRange({ sri: 10, sci: 1, eri: 12, eci: 2 })
store.sortAscending()
const sorted = store.sheetsData[store.spreadsheet.activeSheetId]
assert.equal(sorted[cellKey(10, 1)].value, '1')
assert.equal(sorted[cellKey(10, 2)], undefined)
assert.equal(sorted[cellKey(11, 2)].value, 'two')
assert.equal(sorted[cellKey(12, 2)].value, 'three')
store.updateCellValue({ row: 20, col: 1 }, '=SUM(A21:A23)+$B$22')
store.selectCell({ row: 22, col: 1 })
store.insertRow()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(20, 1)].formula, '=SUM(A21:A24)+$B$23')
store.deleteRow()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(20, 1)].formula, '=SUM(A21:A23)+$B$22')
store.selectRange({ sri: 10, sci: 1, eri: 12, eci: 2 })
store.clearSelectionContents()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(10, 1)].value, '')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(12, 2)].value, '')
store.undo()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(12, 2)].value, 'three')
store.updateCellValue({ row: 30, col: 1 }, '=B30+$C$1')
store.selectCell({ row: 30, col: 1 })
store.autofill({ sri: 30, sci: 1, eri: 32, eci: 1 })
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(31, 1)].formula, '=B31+$C$1')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(32, 1)].formula, '=B32+$C$1')
store.undo()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(31, 1)], undefined)
store.updateCellValue({ row: 31, col: 3 }, '2')
store.updateCellValue({ row: 32, col: 3 }, '4')
store.selectRange({ sri: 31, sci: 3, eri: 32, eci: 3 })
store.autofill({ sri: 30, sci: 3, eri: 34, eci: 3 })
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(30, 3)].value, '0')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(33, 3)].value, '6')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(34, 3)].value, '8')
store.undo()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(34, 3)], undefined)
store.resizeRow(40, 55)
store.selectCell({ row: 40, col: 1 })
store.hideRow()
store.selectCell({ row: 35, col: 1 })
store.insertRow()
assert.equal(store.activeSheet.rowHeights.get(41), 55)
assert.equal(store.activeSheet.hiddenRows.has(41), true)
store.deleteRow()
assert.equal(store.activeSheet.rowHeights.get(40), 55)
assert.equal(store.activeSheet.hiddenRows.has(40), true)
store.selectRange({ sri: 50, sci: 1, eri: 51, eci: 2 })
store.addValidation({ type: 'number', min: 1, max: 5, message: 'Entre 1 et 5', allowBlank: false })
store.updateCellValue({ row: 50, col: 1 }, '3')
store.updateCellValue({ row: 50, col: 1 }, '9')
assert.equal(store.validationError, 'Entre 1 et 5')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(50, 1)].value, '3')
store.selectCell({ row: 50, col: 1 })
store.pasteText('4\t9')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(50, 1)].value, '3')
store.clearValidation()
assert.equal(store.activeSheet.validations.some(v => v.range.sri <= 50 && v.range.eri >= 50 && v.range.sci <= 1 && v.range.eci >= 1), false)
assert.equal(store.activeSheet.validations.some(v => v.range.sri <= 51 && v.range.eri >= 51 && v.range.sci <= 2 && v.range.eci >= 2), true)
store.undo()
assert.equal(store.activeSheet.validations.some(v => v.range.sri <= 50 && v.range.eri >= 50 && v.range.sci <= 1 && v.range.eci >= 1), true)
store.selectCell({ row: 49, col: 1 })
store.insertRow()
assert.equal(store.activeSheet.validations.some(v => v.range.sri === 51 && v.range.eri === 52), true)
store.deleteRow()
assert.equal(store.activeSheet.validations.some(v => v.range.sri === 50 && v.range.eri === 51), true)
store.selectCell({ row: 55, col: 1 })
store.addValidation({ type: 'list', values: ['Oui', 'Non'], allowBlank: false })
store.updateCellValue({ row: 55, col: 1 }, 'Oui')
store.updateCellValue({ row: 55, col: 1 }, 'Autre')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(55, 1)].value, 'Oui')
store.updateCellValue({ row: 55, col: 1 }, 'Non')
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(55, 1)].value, 'Non')
store.undo()
assert.equal(store.sheetsData[store.spreadsheet.activeSheetId][cellKey(55, 1)].value, 'Oui')
store.selectRange({ sri: 10, sci: 1, eri: 12, eci: 2 })
const chartId = store.addChart()!
assert.equal(store.activeSheet.charts?.length, 1)
store.updateChart(chartId, { type: 'line', title: 'Ventes' })
assert.equal(store.activeSheet.charts?.[0].title, 'Ventes')
store.selectCell({ row: 10, col: 1 })
store.insertRow()
assert.equal(store.activeSheet.charts?.[0].range.sri, 11)
store.undo()
assert.equal(store.activeSheet.charts?.[0].range.sri, 10)
store.removeChart(chartId)
assert.equal(store.activeSheet.charts?.length, 0)
store.undo()
assert.equal(store.activeSheet.charts?.length, 1)
store.selectRange({ sri: 60, sci: 1, eri: 62, eci: 2 })
assert.equal(store.saveConditionalFormat({ operator: 'greater', value: '10', backgroundColor: '#c6efce', color: '#006100' }), true)
const ruleId = store.activeSheet.conditionalFormats![0].id
store.saveConditionalFormat({ operator: 'less', value: '5', backgroundColor: '#ffffff', color: '#000000' }, ruleId)
assert.equal(store.activeSheet.conditionalFormats![0].range.sri, 60)
store.selectCell({ row: 59, col: 1 })
store.insertRow()
assert.equal(store.activeSheet.conditionalFormats![0].range.sri, 61)
store.undo()
assert.equal(store.activeSheet.conditionalFormats![0].range.sri, 60)
store.removeConditionalFormat(ruleId)
assert.equal(store.activeSheet.conditionalFormats?.length, 0)
store.undo()
assert.equal(store.activeSheet.conditionalFormats?.length, 1)
store.selectCell({ row: 70, col: 1 })
store.updateCellFormat([{ row: 70, col: 1 }], { bold: true })
assert.equal(store.currentFormat.bold, true)
store.undo()
assert.equal(store.currentFormat.bold, undefined)
assert.equal(store.saveWorkbook(), true)
setActivePinia(createPinia())
const restoredStore = useSpreadsheetStore()
assert.equal(restoredStore.activeSheet.charts?.[0].title, 'Ventes')
assert.equal(restoredStore.activeSheet.charts?.[0].type, 'line')
assert.equal(restoredStore.activeSheet.conditionalFormats?.[0].operator, 'less')
console.log('Store structure checks passed')
